/**
 * The built-in CHIP-8 hexadecimal font: each digit is 5 rows of 4 pixels, stored in the high
 * nibble of each byte. The chip8 era draws numbers with it.
 */
export const HEX_FONT = Object.freeze({
  0: [0xf0, 0x90, 0x90, 0x90, 0xf0],
  1: [0x20, 0x60, 0x20, 0x20, 0x70],
  2: [0xf0, 0x10, 0xf0, 0x80, 0xf0],
  3: [0xf0, 0x10, 0xf0, 0x10, 0xf0],
  4: [0x90, 0x90, 0xf0, 0x10, 0x10],
  5: [0xf0, 0x80, 0xf0, 0x10, 0xf0],
  6: [0xf0, 0x80, 0xf0, 0x90, 0xf0],
  7: [0xf0, 0x10, 0x20, 0x40, 0x40],
  8: [0xf0, 0x90, 0xf0, 0x90, 0xf0],
  9: [0xf0, 0x90, 0xf0, 0x10, 0xf0],
  a: [0xf0, 0x90, 0xf0, 0x90, 0x90],
  b: [0xe0, 0x90, 0xe0, 0x90, 0xe0],
  c: [0xf0, 0x80, 0x80, 0x80, 0xf0],
  d: [0xe0, 0x90, 0x90, 0x90, 0xe0],
  e: [0xf0, 0x80, 0xf0, 0x80, 0xf0],
  f: [0xf0, 0x80, 0xf0, 0x80, 0x80],
});

export const GLYPH_WIDTH = 4;
export const GLYPH_HEIGHT = 5;

/**
 * Lit pixels of a number written with the hex font, one blank column between digits.
 * @param {number} value Non-negative integer.
 * @param {number} [radix] 10 or 16.
 * @returns {{ pixels: { x: number, y: number }[], width: number, text: string }}
 */
export function layoutNumber(value, radix = 10) {
  const text = value.toString(radix);
  const pixels = [...text].flatMap((digit, index) =>
    HEX_FONT[digit].flatMap((row, y) =>
      [0, 1, 2, 3]
        .filter((bit) => (row >> (7 - bit)) & 1)
        .map((bit) => ({ x: index * (GLYPH_WIDTH + 1) + bit, y })),
    ),
  );
  return { pixels, width: text.length * (GLYPH_WIDTH + 1) - 1, text };
}
